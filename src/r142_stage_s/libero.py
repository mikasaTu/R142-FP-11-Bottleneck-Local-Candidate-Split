def _load_qpos_array(path: str | Path) -> np.ndarray:
    """Load a LIBERO ``.pruned_init`` tensor without changing its contents."""

    target = Path(path)
    errors: list[str] = []
    try:
        import torch

        try:
            value = torch.load(target, map_location="cpu", weights_only=False)
        except TypeError:  # torch versions before the weights_only argument
            value = torch.load(target, map_location="cpu")
        if hasattr(value, "detach"):
            value = value.detach().cpu().numpy()
        array = np.asarray(value, dtype=np.float64)
    except Exception as exc:  # noqa: BLE001 - try the NumPy fallback below
        errors.append(f"torch.load: {exc}")
        try:
            value = np.load(target, allow_pickle=False)
            if isinstance(value, np.lib.npyio.NpzFile):
                keys = list(value.files)
                if len(keys) != 1:
                    raise ValueError(f"expected one array in npz, got {keys}")
                value = value[keys[0]]
            array = np.asarray(value, dtype=np.float64)
        except Exception as fallback_exc:  # noqa: BLE001 - report both causes
            errors.append(f"numpy.load: {fallback_exc}")
            raise VariantGenerationError(f"cannot load qpos tensor {target}: {'; '.join(errors)}") from fallback_exc
    if array.ndim == 1:
        array = array[None, :]
    if array.ndim != 2 or not np.all(np.isfinite(array)):
        raise VariantGenerationError(f"qpos tensor {target} must be finite rank-2, got {array.shape}")
    return array


def _write_torch_qpos(path: str | Path, array: np.ndarray) -> None:
    """Atomically write a simulator-generated tensor in LIBERO's format."""

    try:
        import torch
    except Exception as exc:  # noqa: BLE001 - this is an external runtime gate
        raise VariantGenerationError("real B qpos generation requires torch.save") from exc
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(f".{destination.name}.tmp-{os.getpid()}")
    torch.save(torch.as_tensor(np.asarray(array, dtype=np.float64)), temporary)
    with temporary.open("rb") as handle:
        os.fsync(handle.fileno())
    temporary.replace(destination)
    _fsync_directory(destination.parent)


def _sim_state_from_simulator(environment: Any) -> np.ndarray:
    """Read LIBERO's full flattened simulator state from a real wrapper.

    LIBERO ``.pruned_init`` files are produced by
    ``ControlEnv.get_sim_state()``, which is ``sim.get_state().flatten()``
    (time, qpos, and qvel), not by ``sim.data.qpos`` alone.  A duplicate BDDL
    body must therefore increase the flattened state width before the state
    can be used as an init state.  Refusing a qpos-only object here is
    intentional: accepting it would silently create a shape-invalid B run.
    """

    pending = [environment]
    seen: set[int] = set()
    while pending:
        owner = pending.pop(0)
        if owner is None or id(owner) in seen:
            continue
        seen.add(id(owner))
        getter = getattr(owner, "get_sim_state", None)
        if callable(getter):
            try:
                value = getter()
            except Exception:  # noqa: BLE001 - try the strict simulator fallback below
                value = None
            if value is not None:
                array = np.asarray(value, dtype=np.float64).reshape(-1)
                if array.size and np.all(np.isfinite(array)):
                    return array.copy()
        sim = getattr(owner, "sim", None)
        getter = getattr(sim, "get_state", None)
        if callable(getter):
            try:
                state = getter()
                flatten = getattr(state, "flatten", None)
                value = flatten() if callable(flatten) else state
                array = np.asarray(value, dtype=np.float64).reshape(-1)
            except Exception:  # noqa: BLE001 - report a strict state-interface error below
                array = np.empty(0, dtype=np.float64)
            if array.size and np.all(np.isfinite(array)):
                return array.copy()
        for name in ("environment", "env", "unwrapped", "base"):
            child = getattr(owner, name, None)
            if child is not None:
                pending.append(child)
    raise VariantGenerationError(
        "simulator does not expose finite get_sim_state() or sim.get_state().flatten(); "
        "sim.data.qpos alone is not a valid LIBERO .pruned_init state"
    )


def _assert_finite_observation(value: Any, path: str = "observation") -> None:
    """Reject NaN/Inf in the observation returned by a restored init state."""

    if isinstance(value, Mapping):
        for key, child in value.items():
            _assert_finite_observation(child, f"{path}.{key}")
    elif isinstance(value, (list, tuple)):
        for index, child in enumerate(value):
            _assert_finite_observation(child, f"{path}[{index}]")
    elif isinstance(value, np.ndarray):
        if np.issubdtype(value.dtype, np.number) and not np.all(np.isfinite(value)):
            raise VariantGenerationError(f"non-finite restored init observation at {path}")
    elif isinstance(value, (bool, int, float, np.number)):
        if not math.isfinite(float(value)):
            raise VariantGenerationError(f"non-finite restored init observation at {path}")


def _validate_init_state_roundtrip(environment: Any, state: np.ndarray) -> None:
    """Load one flattened state through LIBERO's setter and check its obs."""

    setter = getattr(environment, "set_init_state", None)
    if not callable(setter):
        raise VariantGenerationError(
            "simulator does not expose set_init_state(); cannot validate generated .pruned_init round-trip"
        )
    try:
        observation = setter(np.asarray(state, dtype=np.float64).copy())
    except Exception as exc:  # noqa: BLE001 - preserve the real simulator error
        raise VariantGenerationError(f"generated sim state failed set_init_state round-trip: {exc}") from exc
    if observation is None:
        getter = getattr(environment, "raw_observation", None)
        observation = getter() if callable(getter) else getattr(environment, "observation", None)
    if observation is None:
        raise VariantGenerationError("set_init_state returned no observation for generated sim state")
    _assert_finite_observation(observation)
    restored = _sim_state_from_simulator(environment)
    if restored.shape != state.shape or not np.allclose(restored, state, rtol=0.0, atol=1e-9):
        error = float(np.max(np.abs(restored - state))) if restored.shape == state.shape else float("inf")
        raise VariantGenerationError(
            f"generated sim state changed during set_init_state round-trip: max_abs_error={error}"
        )


def _seed_simulator(environment: Any, seed: int) -> None:
    # LIBERO's BDDL environment delegates to ``numpy.random.seed``, whose
    # legacy API accepts only uint32 seeds.  Keep the manifest's deterministic
    # seed identity while passing the portable uint32 value to real wrappers.
    simulator_seed = int(seed) & 0xFFFFFFFF
    for owner in (environment, getattr(environment, "environment", None)):
        setter = getattr(owner, "seed", None)
        if callable(setter):
            setter(simulator_seed)


def _call_qpos_simulator_factory(
    simulator_factory: Callable[..., Any],
    task_id: int,
    bddl_path: Path,
    seed: int,
) -> Any:
    try:
        return simulator_factory(task_id=int(task_id), bddl_path=str(bddl_path), seed=int(seed))
    except TypeError as keyword_error:
        try:
            return simulator_factory(int(task_id), str(bddl_path), int(seed))
        except TypeError:
            raise keyword_error


def b_init_state_seed(task_id: int, setting_index: int, state_index: int, *, seed_base: int = B_INIT_STATE_SEED_BASE) -> int:
    """Return the frozen deterministic seed for one new B init state."""

    return stable_seed(
        "stage-s", "B", "qpos", int(seed_base), int(setting_index), int(task_id), int(state_index), bytes_count=4
    )


def generate_variant_initial_qpos(
    simulator_factory: Callable[..., Any],
    output_path: str | Path,
    *,
    task_id: int,
    bddl_path: str | Path,
    source_init_path: str | Path,
    count: int = B_INIT_STATE_COUNT,
    seeds: Sequence[int] | None = None,
    qpos_writer: Callable[[str | Path, np.ndarray], None] | None = None,
    require_unique: bool = True,
) -> dict[str, Any]:
    """Generate new qpos rows by resetting the real simulator with fixed seeds.

    The simulator is reset from the generated BDDL itself; no old init state is
    passed to it.  The source tensor is loaded only to prove that the free-joint
    layout grew and that no generated row is an exact old row.
    """

    if int(count) < B_INIT_STATE_COUNT:
        raise VariantGenerationError(f"B requires at least {B_INIT_STATE_COUNT} generated init states, got {count}")
    source_path = Path(source_init_path)
    if not source_path.is_file():
        raise VariantGenerationError(f"missing source init tensor for audit: {source_path}")
    old_array = _load_qpos_array(source_path)
    selected_seeds = tuple(int(value) for value in (seeds if seeds is not None else range(int(count))))
    if len(selected_seeds) != int(count):
        raise VariantGenerationError(f"expected {count} fixed seeds, got {len(selected_seeds)}")
    rows: list[np.ndarray] = []
    for seed in selected_seeds:
        python_state = random.getstate()
        numpy_state = np.random.get_state()
        environment = None
        try:
            random.seed(int(seed))
            np.random.seed(int(seed) & 0xFFFFFFFF)
            environment = _call_qpos_simulator_factory(simulator_factory, int(task_id), Path(bddl_path), int(seed))
            _seed_simulator(environment, int(seed))
            reset = getattr(environment, "reset", None)
            if not callable(reset):
                raise VariantGenerationError("qpos simulator has no reset()")
            try:
                reset()
            except TypeError:
                reset(seed=int(seed))
            state = _sim_state_from_simulator(environment)
            _validate_init_state_roundtrip(environment, state)
            rows.append(state)
        finally:
            if environment is not None and hasattr(environment, "close"):
                environment.close()
            random.setstate(python_state)
            np.random.set_state(numpy_state)
    try:
        generated = np.stack(rows, axis=0).astype(np.float64, copy=False)
    except ValueError as exc:
        raise VariantGenerationError(f"generated qpos rows have inconsistent dimensions: {[row.shape for row in rows]}") from exc
    if generated.shape[0] < B_INIT_STATE_COUNT or generated.shape[0] != int(count):
        raise VariantGenerationError(f"generated qpos has invalid row count {generated.shape[0]}")
    if generated.shape[1] <= old_array.shape[1]:
        raise VariantGenerationError(
            f"B qpos dimension did not grow after duplicate insertion: old={old_array.shape[1]}, new={generated.shape[1]}"
        )
    if require_unique and len({sha256_bytes(row.tobytes()) for row in generated}) != generated.shape[0]:
        raise VariantGenerationError("simulator produced duplicate qpos rows; refusing to call them new init states")
    for row in generated:
        if old_array.shape[1] == generated.shape[1] and any(np.array_equal(row, old) for old in old_array):
            raise VariantGenerationError("simulator-generated qpos contains an exact old init row")
    writer = qpos_writer or _write_torch_qpos
    writer(output_path, generated)
    destination = Path(output_path)
    if not destination.is_file():
        raise VariantGenerationError(f"qpos writer did not create {destination}")
    return {
        "task_id": int(task_id),
        "path": str(destination),
        "sha256": sha256_file(destination),
        "count": int(generated.shape[0]),
        "state_dim": int(generated.shape[1]),
        "source_state_dim": int(old_array.shape[1]),
        "state_format": "sim.get_state().flatten()",
        "seeds": [int(value) for value in selected_seeds],
        "generated_by": "real_libero_offscreen_render_env_reset",
        "old_init_reused": False,
    }


def _resolve_libero_site(libero_root: str | Path) -> Path:
    root = Path(libero_root).resolve()
    # The pinned OpenPI LIBERO fork has a namespace-level ``libero`` folder
    # containing the import package ``libero.libero``.  Accept its project
    # root, namespace root, or inner package path and always return the path
    # that makes ``import libero.libero`` resolve to that fork.  Also support
    # the flatter upstream ``import libero`` layout for a qpos-only smoke.
    if (root / "libero" / "libero" / "envs" / "__init__.py").is_file():
        return root
    if (
        ((root / "setup.py").is_file() or (root.parent / "setup.py").is_file())
        and (root / "libero" / "__init__.py").is_file()
        and (root / "libero" / "envs" / "__init__.py").is_file()
    ):
        return root if (root / "setup.py").is_file() else root.parent
    if (root / "envs" / "__init__.py").is_file() and (root / "__init__.py").is_file():
        return root.parent.parent
    if (root / "libero" / "__init__.py").is_file() and (root / "libero" / "bddl_files").is_dir():
        return root
    if (root / "envs" / "__init__.py").is_file():
        return root.parent
    return root


def make_libero_qpos_simulator_factory(
    libero_root: str | Path,
    *,
    render_gpu_device_id: int = 0,
    camera_height: int = 256,
    camera_width: int = 256,
) -> Callable[..., Any]:
    """Build a factory around the pinned LIBERO OffScreenRenderEnv.

    Imports are intentionally deferred until the first real generation call,
    so CPU-only unit tests never require MuJoCo or the external site package.
    """

    site = _resolve_libero_site(libero_root)

    def factory(*, task_id: int, bddl_path: str, seed: int) -> Any:
        del task_id
        os.environ["QPILOTS_LIBERO_SITE"] = str(site)
        if str(site) not in sys.path:
            sys.path.append(str(site))
        try:
            from libero.libero.envs import OffScreenRenderEnv
        except ModuleNotFoundError as nested_error:
            # A flat LIBERO installation is accepted only for the isolated
            # qpos smoke; Stage-R's maintained wrapper still requires the
            # nested OpenPI fork and will fail closed if it is absent.
            try:
                from libero.envs import OffScreenRenderEnv
            except Exception as flat_error:  # noqa: BLE001 - preserve both import causes
                raise VariantGenerationError(
                    f"cannot import pinned LIBERO OffScreenRenderEnv from {site}: {nested_error}; {flat_error}"
                ) from flat_error
        except Exception as exc:  # noqa: BLE001 - retain the external-runtime cause
            raise VariantGenerationError(f"cannot import pinned LIBERO OffScreenRenderEnv from {site}: {exc}") from exc
        environment = OffScreenRenderEnv(
            bddl_file_name=str(Path(bddl_path).resolve()),
            camera_heights=int(camera_height),
            camera_widths=int(camera_width),
            camera_names=("agentview", "robot0_eye_in_hand"),
            render_gpu_device_id=int(render_gpu_device_id),
        )
        _seed_simulator(environment, int(seed))
        return environment

    return factory


def build_b_variant_matrix(
    source_bddl_root: str | Path,
    source_init_root: str | Path,
    output_root: str | Path,
    *,
    simulator_factory: Callable[..., Any],
    settings: Sequence[float] = PROXIMITY_MAGNITUDES,
    count: int = B_INIT_STATE_COUNT,
    seed_base: int = B_INIT_STATE_SEED_BASE,
    assets_root: str | Path | None = None,
) -> list[dict[str, Any]]:
    """Create all ten BDDL tasks at all four offsets and fresh sim states."""

    frozen_settings = tuple(float(value) for value in settings)
    if frozen_settings != tuple(PROXIMITY_MAGNITUDES):
        raise VariantGenerationError(f"B settings are frozen to {PROXIMITY_MAGNITUDES}, got {frozen_settings}")
    source_bddl = Path(source_bddl_root)
    source_init = Path(source_init_root)
    destination = Path(output_root)
    # Validate the complete source set before creating any variant, so a
    # missing task cannot leave a misleading partially executable matrix.
    source_paths: dict[int, Path] = {}
    for task_id in range(TASK_COUNT):
        task = task_spec(task_id)
        bddl_path = source_bddl / f"{task.name}.bddl"
        init_path = source_init / f"{task.name}.pruned_init"
        if not bddl_path.is_file() or not init_path.is_file():
            raise MissingRegeneratedInitialStates(f"missing frozen LIBERO source task {task_id}: {bddl_path} / {init_path}")
        source_paths[task_id] = bddl_path
    manifests: list[dict[str, Any]] = []
    for setting_index, magnitude in enumerate(frozen_settings):
        setting_id = f"proximity_{magnitude:.2f}m"
        setting_root = destination / setting_id
        generated_root = setting_root / "generated_init_states"
        bddl_dir = setting_root / "bddl_files" / LIBERO_SUITE
        generated_root.mkdir(parents=True, exist_ok=True)
        bddl_dir.mkdir(parents=True, exist_ok=True)
        variants: list[BVariant] = []
        generations: list[dict[str, Any]] = []
        for task_id in range(TASK_COUNT):
            task = task_spec(task_id)
            variant = generate_b_variant(source_paths[task_id], task_id, magnitude)
            variant_bddl = bddl_dir / f"{task.name}.bddl"
            atomic_text(variant_bddl, variant.bddl_text)
            variants.append(variant)
            generations.append(
                generate_variant_initial_qpos(
                    simulator_factory,
                    generated_root / f"{task.name}.pruned_init",
                    task_id=task_id,
                    bddl_path=variant_bddl,
                    source_init_path=source_init / f"{task.name}.pruned_init",
                    count=int(count),
                    seeds=tuple(b_init_state_seed(task_id, setting_index, index, seed_base=int(seed_base)) for index in range(int(count))),
                )
            )
        generated_manifest = {
            "protocol_id": STAGE_S_PROTOCOL_ID,
            "substrate": "B",
            "suite": LIBERO_SUITE,
            "setting_id": setting_id,
            "magnitude_m": float(magnitude),
            "regenerated": True,
            "old_init_reused": False,
            "state_format": "torch.save(sim.get_state().flatten())",
            "init_state_count": int(count),
            "seed_base": int(seed_base),
            "generated_by": "real_libero_offscreen_render_env_reset",
            "tasks": generations,
        }
        atomic_json(generated_root / "REGENERATED_INIT_STATES.json", generated_manifest)
        task_results: list[dict[str, Any]] = []
        for task_id, variant in enumerate(variants):
            task_results.append(
                write_b_variant(
                    variant,
                    setting_root,
                    regenerated_initial_states_root=generated_root,
                    source_init_root=source_init,
                    assets_root=assets_root,
                    write_config=task_id == 0,
                )
            )
        generated_manifest["files"] = {
            str(task_result["task_id"]): task_result["init_states_sha256"] for task_result in task_results
        }
        atomic_json(setting_root / "REGENERATED_INIT_STATES.json", generated_manifest)
        manifests.append(
            {
                "protocol_id": STAGE_S_PROTOCOL_ID,
                "substrate": "B",
                "setting_id": setting_id,
                "magnitude_m": float(magnitude),
                "root": str(setting_root),
                "tasks": task_results,
                "regenerated_init_states": str(setting_root / "REGENERATED_INIT_STATES.json"),
            }
        )
    atomic_json(destination / "B_VARIANT_MATRIX.json", {"protocol_id": STAGE_S_PROTOCOL_ID, "substrate": "B", "settings": manifests})
    return manifests


def _configure_stage_r_sources(qpilots_root: str | Path, libero_root: str | Path) -> tuple[Path, Path]:
    """Apply the pinned Stage-R import roots without importing heavy runtimes."""

    qpilots = Path(qpilots_root).resolve()
    libero_site = _resolve_libero_site(libero_root)
    for value in (qpilots, libero_site):
        if str(value) not in sys.path:
            sys.path.insert(0, str(value))
    os.environ["QPILOTS_LIBERO_SITE"] = str(libero_site)
    return qpilots, libero_site


def _select_libero_config(config_root: str | Path) -> Path:
    """Bind the current process to one run-scoped LIBERO config.

    The pinned LIBERO package snapshots ``LIBERO_CONFIG_PATH`` in module
    globals at first import.  Stage-S B uses four different BDDL roots in one
    calibration process, so merely changing the environment variable is not
    sufficient after rank 0 has constructed its first Task64 environment.
    Update the package globals as well before every environment construction;
    this keeps each setting's BDDL/init-state pair isolated and deterministic.
    """

    root = Path(config_root).expanduser().resolve()
    config_file = root / "config.yaml"
    if not config_file.is_file():
        raise StageSError(f"run-scoped LIBERO config is missing: {config_file}")
    os.environ["LIBERO_CONFIG_PATH"] = str(root)
    for module_name in ("libero.libero", "libero.libero.utils"):
        module = sys.modules.get(module_name)
        if module is not None:
            setattr(module, "libero_config_path", str(root))
            setattr(module, "config_file", str(config_file))
    return root


