def build_pai_stage_s_payload(
    *,
    run_id: str,
    output_root: str | Path,
    log_root: str | Path,
    command: Sequence[str] | None = None,
    working_directory: str | Path | None = None,
    c_contract: Mapping[str, Any] | None = None,
    resource_pool: str = "idle",
    gpu_count: int = PAI_MAX_GPU,
    cpu_cores: int = PAI_MAX_CPU,
    memory_gib: int = PAI_MAX_MEMORY_GIB,
    shared_memory_gib: int = PAI_MAX_MEMORY_GIB,
) -> dict[str, Any]:
    """Build a fail-closed, non-submitting idle-PAI payload.

    The payload describes the exact control-plane contract, persistent resume
    paths, and the two daily Beijing no-job windows.  It intentionally does
    not call DLC/PAI; a separate authorized orchestrator must validate and
    submit it after external credentials and mount readback are available.
    """

    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{2,127}", str(run_id)):
        raise ValueError(f"invalid run_id {run_id!r}")
    if resource_pool not in {"idle", "robot_idle"}:
        raise ValueError(f"Stage-S payload supports robot idle only, got {resource_pool!r}")
    if (int(gpu_count), int(cpu_cores), int(memory_gib), int(shared_memory_gib)) != (
        PAI_MAX_GPU,
        PAI_MAX_CPU,
        PAI_MAX_MEMORY_GIB,
        PAI_MAX_MEMORY_GIB,
    ):
        raise ValueError("Stage-S production payload is frozen to 8 GPU / 88 CPU / 1525 GiB")
    output = Path(output_root).resolve()
    logs = Path(log_root).resolve()
    for name, path in (("output_root", output), ("log_root", logs)):
        if not path.is_absolute():
            raise ValueError(f"{name} must be absolute")
        if not str(path).startswith("/mnt/cpfs/zbl-cpfs-new/"):
            raise ValueError(f"{name} must use the new /mnt/cpfs/zbl-cpfs-new storage namespace")
    if c_contract is not None:
        contract_command = c_contract.get("launcher", {}).get("command") if isinstance(c_contract.get("launcher"), Mapping) else None
        if command is None and contract_command:
            command = [str(value) for value in contract_command]
        if working_directory is None and isinstance(c_contract.get("launcher"), Mapping):
            working_directory = c_contract["launcher"].get("working_directory")
    if command is None:
        raise ValueError("a real foreground command or C launcher contract is required")
    command_values = [str(value) for value in command]
    if not command_values or any(not value for value in command_values):
        raise ValueError("foreground command must be non-empty")
    command_text = " ".join(command_values)
    if "sleep" in command_text or "|| true" in command_text:
        raise ValueError("payload cannot hide failures with sleep or || true")
    for legacy in ("/mnt/cpfs/leon", "/workspace/leon"):
        if legacy in command_text or legacy in str(working_directory or ""):
            raise ValueError(f"payload contains legacy storage prefix {legacy}")
    workdir = str(Path(working_directory).resolve()) if working_directory is not None else str(output)
    checkpoint_root = output / "pi05_libero" / "r142_stage_s_c_undertrained_seed42"
    checkpoint_contract = {
        "save_interval_steps": C_SAVE_INTERVAL,
        "retain_and_audit_steps": list(C_RETAIN_STEPS),
        "full_reference_step": C_FULL_REFERENCE_STEP,
        "full_state_resume": True,
        "startup_repair": True,
        "post_save_failure_fatal": True,
    }
    if c_contract is not None and isinstance(c_contract.get("training_contract"), Mapping):
        declared_steps = tuple(
            int(value)
            for value in c_contract["training_contract"].get("retain_and_audit_steps", C_RETAIN_STEPS)
        )
        declared_interval = int(
            c_contract["training_contract"].get("save_interval_steps", C_SAVE_INTERVAL)
        )
        declared_reference = int(
            c_contract["training_contract"].get("full_reference_step", C_FULL_REFERENCE_STEP)
        )
        if declared_steps != tuple(C_RETAIN_STEPS):
            raise ValueError(f"PAI payload checkpoint steps are frozen to {C_RETAIN_STEPS}, got {declared_steps}")
        if declared_interval != C_SAVE_INTERVAL or declared_reference != C_FULL_REFERENCE_STEP:
            raise ValueError("PAI payload checkpoint schedule does not match the frozen C contract")
        checkpoint_contract.update(
            {
                "save_interval_steps": declared_interval,
                "retain_and_audit_steps": list(declared_steps),
                "full_reference_step": declared_reference,
            }
        )
    payload = {
        "schema": "r142-stage-s-pai-payload-v1",
        "protocol_id": STAGE_S_PROTOCOL_ID,
        "run_id": str(run_id),
        "substrate": "C",
        "label": "WEAK_SUBSTRATE",
        "no_pai_submit_performed": True,
        "ready_for_submission": False,
        "foreground_command": command_values,
        "command": command_values,
        "working_directory": workdir,
        "resource": {
            "resource_pool": str(resource_pool),
            "pool_family": "robot",
            "resource_alias": PAI_ROBOT_IDLE_RESOURCE_ALIAS,
            "resource_id": PAI_ROBOT_IDLE_RESOURCE_ID,
            "quota_name": PAI_ROBOT_IDLE_QUOTA_NAME,
            "oversold_type": "AcceptQuotaOverSold",
            "worker": 1,
            "gpu": PAI_MAX_GPU,
            "gpu_count": PAI_MAX_GPU,
            "cpu": PAI_MAX_CPU,
            "cpu_cores": PAI_MAX_CPU,
            "memory_gib": PAI_MAX_MEMORY_GIB,
            "shared_memory_gib": PAI_MAX_MEMORY_GIB,
            "disable_ecs_stock_check": True,
        },
        "fault_tolerance": {
            "execution_mode": "Sync",
            "policy": "OnFailure",
            "max_num_of_job_restart": 50,
            "launcher_attempts_per_incarnation": 1,
            "persistent_application_autoresume": True,
        },
        "persistence": {
            "checkpoint_root": str(checkpoint_root),
            "requested_output_root": str(output),
            "log_root": str(logs),
            "resume": "discover_newest_complete_same_run_lineage",
            "same_run_id_on_resume": True,
            "full_optimizer_scheduler_rng_state": True,
        },
        "checkpoint_contract": checkpoint_contract,
        "daily_no_job_windows": [dict(window) for window in STAGE_S_NO_JOB_WINDOWS],
        "no_job_window_policy": {
            "timezone": "Asia/Shanghai",
            "stop_before": ["09:30", "19:30"],
            "resume_after": ["09:40", "19:40"],
            "fail_closed": True,
        },
        "identity": {"runtime_uid": 2254, "runtime_gid": 2254, "ownership_probe_required": True},
        "fail_closed": True,
    }
    return payload


def write_pai_stage_s_payload(path: str | Path, payload: Mapping[str, Any]) -> dict[str, Any]:
    """Atomically write a previously validated Stage-S PAI payload."""

    if payload.get("no_pai_submit_performed") is not True or payload.get("fail_closed") is not True:
        raise ValueError("payload must be explicitly non-submitting and fail-closed")
    atomic_json(path, dict(payload))
    return dict(payload)


def import_callback(spec: str) -> Callable[..., Any]:
    """Load ``module:function`` for the real-runtime scripts."""

    if ":" not in spec:
        raise ValueError("callback must have module:function form")
    module, function = spec.split(":", 1)
    value = getattr(importlib.import_module(module), function)
    if not callable(value):
        raise TypeError(f"callback {spec} is not callable")
    return value


